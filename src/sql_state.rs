use crate::ident::sql_to_rs_ident;
use crate::ident::CaseType::Pascal;
use phf::phf_map;
use proc_macro2::TokenStream;
use quote::ToTokens;
use std::hash::{Hash, Hasher};
use std::ops::Deref;

#[derive(Clone, Eq, Debug)]
pub struct SqlState(tokio_postgres::error::SqlState);

impl Default for SqlState {
    fn default() -> Self {
        Self(tokio_postgres::error::SqlState::RAISE_EXCEPTION)
    }
}

impl PartialEq for SqlState {
    fn eq(&self, other: &Self) -> bool {
        self.0.code() == other.0.code()
    }
}

impl Hash for SqlState {
    fn hash<H: Hasher>(&self, state: &mut H) {
        self.0.code().hash(state); // Hashing only the string code
    }
}

impl PartialOrd for SqlState {
    fn partial_cmp(&self, other: &Self) -> Option<std::cmp::Ordering> {
        Some(self.cmp(other))
    }
}

impl Ord for SqlState {
    fn cmp(&self, other: &Self) -> std::cmp::Ordering {
        self.0.code().cmp(other.0.code())
    }
}

impl Deref for SqlState {
    type Target = tokio_postgres::error::SqlState;

    fn deref(&self) -> &Self::Target {
        &self.0
    }
}

impl SqlState {
    pub fn from_code(code: &str) -> Self {
        Self(tokio_postgres::error::SqlState::from_code(code))
    }

    /// The condition name (`unique_violation`, `no_data_found`) for a standard
    /// SQLSTATE; `None` for application-defined codes.
    pub fn symbolic_name(&self) -> Option<&'static str> {
        SQL_STATE_NAMES.get(self.0.code()).copied()
    }

    /// Rust identifier for this state: `UniqueViolation`, `NoDataFound`, or
    /// the raw code (`M0422`) when there is no standard name.
    pub fn rs_name(&self) -> TokenStream {
        sql_to_rs_ident(self.symbolic_name().unwrap_or(self.code()), Pascal)
    }
}

impl ToTokens for SqlState {
    fn to_tokens(&self, tokens: &mut TokenStream) {
        tokens.extend(self.rs_name())
    }
}

